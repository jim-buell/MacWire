"""Convert the approved PSD's exported poses into monochrome Toolbox cursors.

Run with Python and Pillow from any directory. The strip contains 16x16 poses in PSD layer order, composited with the
always-visible BG layer. Original black/white pixels and transparency are retained.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]


def generate():
    strip = Image.open(ROOT / 'assets/wait-cursor.png').convert('RGBA')
    assert strip.height == 16 and strip.width % 16 == 0
    count = strip.width // 16
    assert 2 <= count <= 64
    sequence = list(range(count)) + list(range(count-2, 0, -1))
    # Match the approved preview easing, quantized to the classic 60 Hz clock.
    milliseconds = [round((70 + 50 * abs(2*i/(count-1)-1)**2)/10)*10 for i in sequence]
    durations = [round(ms*60/1000) for ms in milliseconds]
    lines = ['/* Generated by tools/generate_wait_cursor.py; do not edit. */',
             f'static Cursor kWireCursors[{count}] = {{']
    for frame in range(count):
        data, mask = [], []
        for y in range(16):
            bits, opaque = 0, 0
            for x in range(16):
                r, g, b, a = strip.getpixel((frame * 16 + x, y))
                assert a in (0, 255) and (not a or (r, g, b) in ((0, 0, 0), (255, 255, 255)))
                if a:
                    opaque |= 0x8000 >> x
                    if r == 0:
                        bits |= 0x8000 >> x
            data.append(bits)
            mask.append(opaque)
        lines += ['    {',
                  '        {' + ', '.join('0x%04X' % v for v in data) + '},',
                  '        {' + ', '.join('0x%04X' % v for v in mask) + '},',
                  '        {8, 8}', '    },']
    lines += ['};', '',
              'static const unsigned char kWireSequence[] = {',
              '    ' + ', '.join(map(str, sequence)),
              '};', '',
              '/* 60 Hz ticks: approximately 120, 100, 80, 70 ms near each end. */',
              'static const unsigned char kWireDuration[] = {',
              '    ' + ', '.join(map(str, durations)),
              '};', '', f'#define kWireSequenceLength {len(sequence)}', f'#define kWireCycleTicks {sum(durations)}', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    (ROOT / 'WaitCursorFrames.h').write_text(generate())
